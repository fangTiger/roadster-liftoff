// 浏览器验收：真实首页点击与机器人比赛，不连接钱包、不发交易。
import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const out = 'recordings/race-polish';
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const errors = [], warnings = [], checks = [];
try {
 const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
 page.on('pageerror', e => errors.push(e.message));
 page.on('console', e => { if (e.type() === 'error') errors.push(e.text()); if (e.type() === 'warning') warnings.push(e.text()); });
 await page.addInitScript(() => { if (!localStorage.getItem('liftoff.lang.v1')) localStorage.setItem('liftoff.lang.v1', 'zh'); });
 await page.goto('http://127.0.0.1:8932/');
 await page.locator('[data-mode=race]').waitFor({ state: 'visible', timeout: 120000 });
 await page.screenshot({ path: `${out}/01-home-zh.png` });
 await page.locator('[data-mode=season]').click(); await page.getByText('敬请期待', { exact: true }).waitFor();
 assert.equal(await page.locator('.ui-loading').isVisible(), true); checks.push('赛季只显示敬请期待');
 await page.locator('[data-mode=race]').click();
 await page.locator('#race-pick').waitFor({ timeout: 120000 });
 await page.locator('#race-loading').waitFor({ state: 'detached' });
 await page.screenshot({ path: `${out}/02-track-picker-zh.png` });
 await page.locator('[data-home]').click();
 await page.locator('[data-mode=race]').waitFor({ state: 'visible', timeout: 120000 }); checks.push('选图返回首页');
 await page.locator('.ui-start-lang .lang-toggle').click();
 await page.getByRole('button', { name: 'Circuit Race', exact: true }).waitFor();
 assert.equal(await page.locator('.ui-loading').evaluate(el => el.classList.contains('ui-leaving')), false);
 await page.screenshot({ path: `${out}/03-home-en.png` });
 await page.locator('[data-mode=race]').click(); await page.locator('#race-pick').waitFor({ timeout: 120000 });
 await page.getByText('Choose a track', { exact: true }).waitFor();
 await page.locator('#race-loading').waitFor({ state: 'detached' });
 await page.screenshot({ path: `${out}/04-track-picker-en.png` });
 await page.locator('[data-board]').click(); await page.getByText('My First Lap NFT', { exact: true }).waitFor();
 await page.waitForFunction(() => getComputedStyle(document.querySelector('.rc-button')).minHeight === '42px');
 await page.waitForTimeout(350);
 await page.screenshot({ path: `${out}/05-records-en.png` });
 await page.locator('#race-tools .lang-toggle').click();
 await page.getByText('我的首圈 NFT', { exact: true }).waitFor(); checks.push('链上面板实时语言切换');
 await page.goto('http://127.0.0.1:8932/?race&autopilot&map=easy');
 await page.locator('#race-hud').waitFor({ timeout: 120000 });
 await page.locator('#race-tools [data-settings]').click();
 await page.locator('#race-tools [type=checkbox]').check();
 assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('liftoff.audio.v1')).muted), true);
 await page.locator('#race-tools [type=checkbox]').uncheck();
 await page.locator('#race-tools [data-settings]').click(); checks.push('竞速静音与原音频存储同步');
 await page.locator('canvas').first().click({ position: { x: 700, y: 450 } });
 console.log('机器人已发车，等待真实第一圈');
 await page.locator('#ach-toast.ach-toast-show').waitFor({ state: 'visible', timeout: 180000 });
 assert.match(await page.locator('#ach-toast').innerText(), /第一圈/);
 await page.screenshot({ path: `${out}/06-first-lap-achievement-zh.png` });
 await page.locator('#race-tools [data-ach]').click(); await page.locator('.ach-panel-visible').waitFor();
 assert.equal(await page.locator('.ach-item').count(), 28);
 await page.screenshot({ path: `${out}/07-achievements-zh.png` });
 await page.locator('.ach-panel-close').click();
 await page.waitForTimeout(350);
 await page.locator('#race-tools .lang-toggle').click();
 await page.getByText('Achievement Unlocked · First Lap', { exact: true }).waitFor();
 await page.screenshot({ path: `${out}/08-race-hud-en.png` });
 console.log('第一圈与28项成就通过，等待完赛');
 await page.locator('.rh-result').waitFor({ state: 'visible', timeout: 240000 });
 await page.getByText('Record onchain', { exact: true }).waitFor();
 await page.waitForFunction(() => getComputedStyle(document.querySelector('.rc-button')).minHeight === '42px');
 await page.waitForTimeout(350);
 assert.ok((await page.locator('#race-chain-slot').boundingBox()).y > (await page.locator('.rh-result').boundingBox()).y + (await page.locator('.rh-result').boundingBox()).height);
 await page.screenshot({ path: `${out}/09-results-en.png` });
 const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('liftoff.achievements.v1')));
 assert.ok(saved.unlocked.first_lap); checks.push('机器人三圈、真实成就解锁、成绩和上链面板英文');
 // 回到原玩法，确认入口仍可启动。
 await page.goto('http://127.0.0.1:8932/');
 await page.locator('[data-mode=space]').waitFor({ state: 'visible', timeout: 120000 });
 await page.locator('[data-mode=space]').click();
 await page.locator('.ui-loading').waitFor({ state: 'hidden' }); await page.keyboard.down('w'); await page.waitForTimeout(600); await page.keyboard.up('w');
 await page.screenshot({ path: `${out}/10-space-regression-en.png` }); checks.push('原玩法开始与加速回归');
 // 手动模式验证成就面板关闭后仍能立即用键盘驾驶。
 await page.goto('http://127.0.0.1:8932/?race&map=easy');
 await page.locator('#race-pick').waitFor({ timeout: 120000 });
 await page.locator('[data-k=easy]').click(); await page.locator('#race-hud').waitFor({ timeout: 120000 });
 await page.waitForFunction(() => !document.querySelector('.rh-notice')?.textContent.trim());
 await page.locator('#race-tools [data-ach]').click(); await page.keyboard.press('Escape');
 await page.keyboard.down('w'); await page.waitForTimeout(1200); await page.keyboard.up('w');
 assert.ok(Number(await page.locator('.rh-speed strong').innerText()) > 10);
 checks.push('成就面板关闭后键盘驾驶恢复');
 assert.deepEqual(errors, []);
 console.log(JSON.stringify({ errors, checks, warnings }));
} finally {
 await writeFile(`${out}/browser-result.json`, JSON.stringify({ errors, warnings, checks }, null, 2));
 await browser.close();
}
